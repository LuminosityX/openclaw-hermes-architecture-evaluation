import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const root=path.resolve(import.meta.dirname,'..'),src=path.join(root,'sources/openclaw');
const stateDir=path.join(root,'fixtures/extended-controls/openclaw-state-'+Date.now());
fs.mkdirSync(stateDir,{recursive:true});
process.env.OPENCLAW_STATE_DIR=stateDir;
process.env.OPENCLAW_CONFIG_PATH=path.join(stateDir,'openclaw.json');
fs.writeFileSync(process.env.OPENCLAW_CONFIG_PATH,JSON.stringify({agents:{entries:{bench:{workspace:path.join(stateDir,'workspace')}}}}));
const {CronService}=await import(pathToFileURL(path.join(src,'src/cron/service.ts')));
const {GatewayScheduler}=await import(pathToFileURL(path.join(src,'src/infra/gateway-scheduler.ts')));
const storePath=path.join(root,'fixtures/extended-controls/openclaw-cron-'+Date.now()+'.json');
const scheduler=new GatewayScheduler();
const noop=()=>{};
const deps={scheduler,storePath,cronEnabled:false,defaultAgentId:'bench',log:{info:noop,warn:noop,error:noop,debug:noop},enqueueSystemEvent:noop,requestHeartbeatNow:noop,runIsolatedAgentJob:async()=>({status:'ok'}),isAgentAvailable:()=>true};
const cron=new CronService(deps),cases=[];
const check=(name,actual,expected)=>cases.push({name,actual,expected,passed:JSON.stringify(actual)===JSON.stringify(expected)});
check('initial_empty',(await cron.list({includeDisabled:true})).length,0);
const a=await cron.add({agentId:'bench',name:'controls-a',enabled:true,schedule:{kind:'every',everyMs:3600000},sessionTarget:'main',wakeMode:'next-heartbeat',payload:{kind:'systemEvent',text:'synthetic controls-a'}});
check('created_id',typeof a.id==='string'&&a.id.length>0,true);
check('created_name',a.name,'controls-a');
check('created_payload',a.payload.text,'synthetic controls-a');
const b=await cron.add({agentId:'bench',name:'controls-b',enabled:true,schedule:{kind:'every',everyMs:7200000},sessionTarget:'main',wakeMode:'next-heartbeat',payload:{kind:'systemEvent',text:'synthetic controls-b'}});
check('unique_ids',a.id!==b.id,true);
check('list_two',(await cron.list({includeDisabled:true})).length,2);
await cron.update(a.id,{enabled:false});
check('pause_persisted',(await cron.list({includeDisabled:true})).find(x=>x.id===a.id)?.enabled,false);
check('paused_hidden',(await cron.list()).some(x=>x.id===a.id),false);
await cron.update(a.id,{enabled:true});
check('resume_visible',(await cron.list()).some(x=>x.id===a.id),true);
await cron.update(a.id,{name:'controls-renamed'});
check('rename_persisted',(await cron.list({includeDisabled:true})).find(x=>x.id===a.id)?.name,'controls-renamed');
const reloaded=new CronService({...deps,scheduler:new GatewayScheduler()});
check('reload_persistent_store',(await reloaded.list({includeDisabled:true})).find(x=>x.id===a.id)?.name,'controls-renamed');
await cron.remove(a.id);
check('remove_visible',(await cron.list({includeDisabled:true})).some(x=>x.id===a.id),false);
await cron.remove(b.id);
check('all_removed',(await cron.list({includeDisabled:true})).length,0);
cron.stop();reloaded.stop();
const file=path.join(root,'raw/extended-controls/openclaw.json');
const out=JSON.parse(fs.readFileSync(file));out[10]=cases;fs.writeFileSync(file,JSON.stringify(out,null,2));
console.log(JSON.stringify({passed:cases.filter(x=>x.passed).length,total:cases.length,storePath}));
process.exit(0);
